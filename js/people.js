document.addEventListener('DOMContentLoaded', (ev) => {
    const peopleContainerOne = document.getElementById('people-container-1')
    const peopleContainerTwo = document.getElementById('people-container-2')
    people.forEach((person, iter) => {
        if (iter <= 5) {
            peopleContainerOne.appendChild(renderPerson(person))
        } else {
            peopleContainerTwo.appendChild(renderPerson(person))
        }
    })
})

function showPeople() {
    const elements = document.querySelectorAll('.people-hide');
    elements.forEach(el => {
        el.classList.remove('people-hide');
        el.classList.add('people-show')
    })

    document.getElementById('show-more-people-button').style.display = 'none';
    document.getElementById('show-less-people-button').style.display = 'inline-block';
}

function hidePeople() {
    const elements = document.querySelectorAll('.people-show');
    elements.forEach(el => {
        el.classList.remove('people-show');
        el.classList.add('people-hide')
    })

    document.getElementById('show-more-people-button').style.display = 'inline-block';
    document.getElementById('show-less-people-button').style.display = 'none';
}

function addPerson(name, title, specialty, imgUrl, contactLinks) {
    const person = {
        name: name,
        title: title,
        specialty: specialty,
        imgUrl: imgUrl,
        contactLinks: contactLinks
    }

    people.push(person)
}

function renderPerson(person, index) {
    let mainDiv = document.createElement('div')
    mainDiv.className = 'people-block'
    if (index >= 6) { // Show first 6, hide the rest
        mainDiv.classList.add('people-hide')
    }

    let img = mainDiv.appendChild(document.createElement('img'))
    img.src = person.imgUrl
    img.className = 'person'

    let nameDiv = mainDiv.appendChild(document.createElement('div'))
    nameDiv.className = 'name'
    nameDiv.innerText = person.name

    let titleDiv = mainDiv.appendChild(document.createElement('div'))
    titleDiv.className = 'title'
    titleDiv.innerText = person.title

    let specialtyDiv = mainDiv.appendChild(document.createElement('div'))
    specialtyDiv.className = 'specialty'
    specialtyDiv.innerText = person.specialty

    let contactLinksDiv = mainDiv.appendChild(document.createElement('div'))
    contactLinksDiv.className = 'contact-links'
    person.contactLinks.forEach(link => {
        let linkElement = document.createElement('a')
        linkElement.href = link.linkUrl

        let iconElement = document.createElement('img')
        iconElement.src = link.iconSrc
        iconElement.className = 'icon'
        linkElement.appendChild(iconElement)

        contactLinksDiv.appendChild(linkElement)
    })

    return mainDiv
}

function randomizeOrder(list) {
    /*
     * Randomizes the order of any array, maintaining the original first and last element
     */
    const size = list.length
    if (size < 3)
        return

    let currentIndex = size - 1

    while (currentIndex > 1) {
        let randomIndex = Math.floor(Math.random() * currentIndex) + 1
        currentIndex -= 1;
        let temp = list[currentIndex]
        list[currentIndex] = list[randomIndex]
        list[randomIndex] = temp
    }
}